"use strict";
const fs = require("node:fs");
const os = require("node:os");
const path = require("node:path");
const Ajv = require("ajv/dist/2020").default;
const standalone = require("ajv/dist/standalone").default;
const esbuild = require("esbuild");
const scratch = fs.mkdtempSync(path.join(os.tmpdir(), "ais-webmcp-js-"));

const LICENSE_FILE = /^licen[cs]e(\.(md|txt))?$/i;

// Every npm package esbuild actually bundled (from the metafile), with its
// full license text. Generic on purpose: a new transitive runtime dependency
// cannot ship in register.js (local asset or CDN copy) without its license.
function bundledPackages(metafile) {
  const roots = new Set();
  for (const input of Object.keys(metafile.inputs)) {
    const parts = input.split("/");
    const at = parts.lastIndexOf("node_modules");
    if (at < 0) continue;
    const depth = parts[at + 1].startsWith("@") ? 2 : 1;
    roots.add(path.resolve(...parts.slice(0, at + 1 + depth)));
  }
  return [...roots]
    .map((root) => {
      const pkg = JSON.parse(
        fs.readFileSync(path.join(root, "package.json"), "utf8"),
      );
      const file = fs.readdirSync(root).find((name) => LICENSE_FILE.test(name));
      if (!file)
        throw new Error(`bundled package ${pkg.name} has no LICENSE file`);
      const text = fs.readFileSync(path.join(root, file), "utf8").trim();
      if (text.includes("*/"))
        throw new Error(`license text of ${pkg.name} would end the banner`);
      return {
        name: pkg.name,
        version: pkg.version,
        license: pkg.license,
        text,
      };
    })
    .sort((a, b) => a.name.localeCompare(b.name));
}

const PACKAGE_VERSION =
  /^(?:0|[1-9][0-9]*)\.(?:0|[1-9][0-9]*)\.(?:0|[1-9][0-9]*)(?:-[0-9A-Za-z.-]+)?(?:\+[0-9A-Za-z.-]+)?$/;

function injectPackageVersion(code, version) {
  if (!PACKAGE_VERSION.test(version)) {
    throw new Error(`package.json version is not a safe semver: ${version}`);
  }
  const pattern = /version\s*:\s*"0\.0\.0"/g;
  const matches = code.match(pattern);
  if (!matches || matches.length !== 1) {
    throw new Error("runtime version marker must appear exactly once");
  }
  return code.replace(/version\s*:\s*"0\.0\.0"/, `version:"${version}"`);
}

function thirdPartyLicenseBanner(metafile) {
  const packages = bundledPackages(metafile);
  if (packages.length === 0) throw new Error("no bundled packages found");
  return (
    "Bundled third-party software, each under its own license:\n" +
    packages
      .map((p) => `\n== ${p.name}@${p.version} (${p.license}) ==\n${p.text}\n`)
      .join("")
  );
}
try {
  const ajv = new Ajv({
    code: { source: true },
    strict: false,
    validateFormats: false,
  });
  // Compile the Draft 2020-12 meta-schema once at build time. Browsers never
  // compile schemas, use eval/new Function, or fetch remote schema references.
  const manifest = JSON.parse(
    fs.readFileSync(
      "src/ais_webmcp/schema/webmcp-manifest.schema.json",
      "utf8",
    ),
  );
  // The explicit host adapter chooses its profile. Browser validation checks
  // document shape; the Dev/CI validator additionally checks allowed names.
  delete manifest.properties.profile.enum;
  ajv.addSchema(manifest);
  ajv.getSchema(manifest.$id);
  fs.writeFileSync(
    path.join(scratch, "schema-validator.cjs"),
    standalone(ajv, {
      validateInputSchema: "https://json-schema.org/draft/2020-12/schema",
      validateManifest: manifest.$id,
    }),
  );
  fs.writeFileSync(
    path.join(scratch, "register.cjs"),
    fs.readFileSync("js/register.source.cjs"),
  );
  // Source keeps a single 0.0.0 marker. The built bundle reports package.json,
  // which publish syncs to the Python package version before this build.
  const packageVersion = JSON.parse(
    fs.readFileSync("package.json", "utf8"),
  ).version;
  const result = esbuild.buildSync({
    entryPoints: [path.join(scratch, "register.cjs")],
    bundle: true,
    platform: "browser",
    format: "cjs",
    target: "es2022",
    write: false,
    minify: true,
    nodePaths: [path.resolve("node_modules")],
    legalComments: "inline",
    metafile: true,
  });
  const output =
    "/* Generated by npm run build:js; do not edit.\n" +
    thirdPartyLicenseBanner(result.metafile) +
    "*/\n(function () {\n" +
    injectPackageVersion(result.outputFiles[0].text, packageVersion) +
    "\n})();\n";
  const target = "src/ais_webmcp/assets/register.js";
  if (process.argv.includes("--check")) {
    if (!fs.existsSync(target) || fs.readFileSync(target, "utf8") !== output)
      throw new Error("register.js is stale; run npm run build:js");
  } else fs.writeFileSync(target, output);
} finally {
  fs.rmSync(scratch, { recursive: true, force: true });
}
