"""Write a starter WebMCP manifest. Scaffold only; no live page and no Django.

The starter is the webpage profile payload (the same document as the valid
webpage fixture) plus one note that this file came from ``ais-webmcp init``.
``subscribe_newsletter`` stays consequential and ``enabled: false``.
"""

from __future__ import annotations

import difflib
import json
from dataclasses import dataclass
from pathlib import Path
from typing import Any

from insight_ui_webmcp.profiles.webpage import WebpageProfile
from insight_ui_webmcp.validate import validate_data

_MANIFEST_SUFFIXES = {".json", ".yaml", ".yml"}
_DEFAULT_NAME = "manifest.yaml"

# Kept in the document (not only a file comment) so JSON scaffolds say it too.
STARTER_NOTE = (
    "Generated by ais-webmcp init. Starter only: no Origin Trial token, "
    "no live-page registration. subscribe_newsletter stays consequential "
    "and enabled false. Static hosts copy register.js from the "
    "insight-ui-webmcp package; Django hosts use "
    "{% load webmcp_tags %}{% webmcp_assets %}."
)

_YAML_HEADER = """\
# Starter WebMCP manifest from `ais-webmcp init`.
# Check it with `ais-webmcp validate`. List tools with `ais-webmcp list`.
# subscribe_newsletter is consequential and enabled: false. Do not opt in here.
# No Origin Trial token is included. Unregister is AbortController / { signal }
# on registerTool, not unregisterTool.
"""

_INDEX_HTML = """\
<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="utf-8">
  <title>WebMCP static host (starter)</title>
  <!--
    Origin Trial is a host concern. Add a meta http-equiv origin-trial tag,
    or an Origin-Trial response header, only where the token is configured.
    This scaffold never includes a token.
  -->
</head>
<body>
  <main>
    <h1>WebMCP starter</h1>
    <p>
      Tools live in <a href="{manifest}">{manifest}</a>.
      This page does not register them. Copy <code>register.js</code> from
      the insight-ui-webmcp package and call
      <code>InsightUiWebmcp.registerFromManifest</code> from the host.
    </p>
  </main>
  <script src="webmcp.js"></script>
</body>
</html>
"""

_WEBMCP_JS = """\
/**
 * Static bootstrap stub from `ais-webmcp init --static`.
 *
 * Not a second WebMCP client. The real helper is register.js in the
 * insight-ui-webmcp package (feature-detect document.modelContext, await
 * registerTool, unregister with AbortController / { signal }).
 *
 * This file does not register tools and does not embed an Origin Trial token.
 * subscribe_newsletter stays enabled: false in the starter manifest.
 */
(function (global) {
  "use strict";
  var context = global.document && global.document.modelContext;
  var supported = !!(context && typeof context.registerTool === "function");
  if (!supported) {
    return;
  }
  global.console.info(
    "ais-webmcp: document.modelContext is present. Load register.js to register tools from the starter manifest."
  );
})(typeof window !== "undefined" ? window : globalThis);
"""

_DJANGO_SNIPPET = (
    "Django host snippet (printed, not written):\n  {% load webmcp_tags %}{% webmcp_assets %}"
)


@dataclass(frozen=True, slots=True)
class ScaffoldFile:
    """One file the scaffold would write."""

    path: Path
    text: str


@dataclass(frozen=True, slots=True)
class ScaffoldResult:
    """Outcome of ``ais-webmcp init``. ``report`` is the full stdout text."""

    exit_code: int
    report: str


def starter_manifest() -> dict[str, Any]:
    """Webpage starter document. Raises if it would fail ``validate``."""
    payload = WebpageProfile().build_manifest(version="1").to_dict()
    notes = list(payload.get("notes") or [])
    notes.append(STARTER_NOTE)
    payload["notes"] = notes
    checked = validate_data(payload, source="<ais-webmcp init>")
    if not checked.ok:
        details = "; ".join(f"{issue.path}: {issue.message}" for issue in checked.issues)
        raise RuntimeError(f"starter manifest failed validation: {details}")
    subscribe = next(tool for tool in payload["tools"] if tool.get("id") == "subscribe_newsletter")
    if subscribe.get("consequential") is not True or subscribe.get("enabled") is not False:
        raise RuntimeError("starter must keep subscribe_newsletter consequential and disabled")
    return payload


def render_manifest(payload: dict[str, Any], suffix: str) -> str:
    """Serialize a starter manifest. YAML files include a short header comment."""
    if suffix.lower() == ".json":
        return json.dumps(payload, indent=2, ensure_ascii=False) + "\n"
    if suffix.lower() in {".yaml", ".yml"}:
        try:
            import yaml
        except ImportError as exc:
            raise RuntimeError(
                "PyYAML is required to write a YAML manifest. "
                "Install pyyaml (Django is not required; see issue #15)."
            ) from exc
        body = yaml.safe_dump(
            payload,
            sort_keys=False,
            allow_unicode=True,
            default_flow_style=False,
        )
        return _YAML_HEADER + body
    raise ValueError(f"unsupported manifest suffix {suffix!r}")


def resolve_manifest_path(output: Path | None) -> Path:
    """Resolve ``--output`` to a manifest file path.

    A directory (existing, or a path with no suffix) receives ``manifest.yaml``.
    """
    if output is None:
        return Path.cwd() / _DEFAULT_NAME
    if output.exists() and output.is_dir():
        return output / _DEFAULT_NAME
    if output.suffix.lower() in _MANIFEST_SUFFIXES:
        return output
    if output.suffix == "":
        return output / _DEFAULT_NAME
    raise ValueError(f"output {output} must be a .json, .yaml, or .yml file, or a directory")


def planned_files(manifest_path: Path, *, static: bool) -> tuple[ScaffoldFile, ...]:
    """Return the files init would write, without touching the filesystem."""
    payload = starter_manifest()
    files = [
        ScaffoldFile(
            path=manifest_path,
            text=render_manifest(payload, manifest_path.suffix),
        )
    ]
    if static:
        directory = manifest_path.parent
        files.append(
            ScaffoldFile(
                path=directory / "index.html",
                text=_INDEX_HTML.format(manifest=manifest_path.name),
            )
        )
        files.append(ScaffoldFile(path=directory / "webmcp.js", text=_WEBMCP_JS))
    return tuple(files)


def _diff_summary(path: Path, new_text: str) -> str:
    if not path.is_file():
        return f"create: {path}"
    try:
        old = path.read_text(encoding="utf-8")
    except (OSError, UnicodeError) as exc:
        return f"force: replacing {path} (could not read existing file: {exc})\n"
    if old == new_text:
        return f"unchanged: {path}"
    diff = "".join(
        difflib.unified_diff(
            old.splitlines(keepends=True),
            new_text.splitlines(keepends=True),
            fromfile=f"a/{path.name}",
            tofile=f"b/{path.name}",
        )
    )
    added = sum(
        1 for line in diff.splitlines() if line.startswith("+") and not line.startswith("+++")
    )
    removed = sum(
        1 for line in diff.splitlines() if line.startswith("-") and not line.startswith("---")
    )
    body = diff if diff.endswith("\n") or not diff else diff + "\n"
    return f"force: replacing {path} (+{added}/-{removed})\n{body}"


def init_manifest(
    output: Path | None = None,
    *,
    force: bool = False,
    static: bool = False,
) -> ScaffoldResult:
    """Write the starter manifest. Refuse to clobber unless ``force``."""
    try:
        manifest_path = resolve_manifest_path(output)
        files = planned_files(manifest_path, static=static)
    except (RuntimeError, ValueError) as exc:
        return ScaffoldResult(exit_code=2, report=f"error: {exc}\n")

    existing = [item.path for item in files if item.path.exists()]
    if existing and not force:
        listed = "\n".join(f"- {path}" for path in existing)
        return ScaffoldResult(
            exit_code=1,
            report=(f"refusing to overwrite existing files (pass --force to replace):\n{listed}\n"),
        )
    blocked = [path for path in existing if path.is_dir()]
    if blocked:
        listed = "\n".join(f"- {path}" for path in blocked)
        return ScaffoldResult(
            exit_code=2,
            report=f"error: output path is a directory, not a file:\n{listed}\n",
        )

    summaries = [_diff_summary(item.path, item.text) for item in files] if force else []
    try:
        for item in files:
            item.path.parent.mkdir(parents=True, exist_ok=True)
            temporary = item.path.with_name(f".{item.path.name}.ais-webmcp-tmp")
            temporary.write_text(item.text, encoding="utf-8")
            temporary.replace(item.path)
    except OSError as exc:
        return ScaffoldResult(
            exit_code=2,
            report=f"error: cannot write scaffold: {exc.strerror or exc}\n",
        )

    lines = [f"wrote {item.path}" for item in files]
    if summaries:
        lines.append("")
        lines.extend(summaries)
    lines.append("")
    lines.append(_DJANGO_SNIPPET)
    return ScaffoldResult(exit_code=0, report="\n".join(lines).rstrip() + "\n")
